// Package simdcodegen checks that the codegen of SIMD machine ops agrees
// with their op table entries.
package simdcodegen

import (
	"fmt"
	"path/filepath"
	"slices"
	"strings"

	"github.com/josharian/unruly/analysis"
	"github.com/josharian/unruly/ops"
	"github.com/josharian/unruly/rules"
)

var Analyzer = &analysis.Analyzer{
	Name: "simdcodegen",
	Doc: `report SIMD ops whose codegen disagrees with their op table entry

Rules produce SIMD machine ops, but what an op computes is decided by the
arch's codegen (cmd/compile/internal/<arch>/simdssa.go and the helpers it
calls). Both are generated by simdgen from different templates, and they
can drift apart. For each SIMD op, the analyzer finds the codegen that emits
it and checks that:

  - an op with an aux (an immediate, a symbol and offset) has codegen that
    reads it, and codegen that reads an aux belongs to an op that has one.
    For example, VPSLLDMasked512constMerging (aux UInt8) is emitted by
    simdV2kvResultInArg0, which never reads v.AuxInt, so
    x.ShiftAllLeft(3).IfElse(m, z) fails to assemble ("invalid instruction:
    VPSLLD Z0, K1, Z1").
  - an op with a SymValAndOff aux decodes it as a ValAndOff; otherwise the
    packed immediate is added to the address.
  - every register argument is read, except arg0 of a resultInArg0 op, which
    is the destination; an unread argument is silently ignored.
  - codegen does not read v.Args[i] beyond the op's argLength, which panics.
  - every op defined in a simd*ops.go file has codegen; otherwise compiling
    it fails with "genValue not implemented".
  - on AMD64, a masked op that is not a merging op is emitted with
    zeroing-masking ({z}), and a merging op is not: without {z}, the
    masked-off lanes keep whatever the output register held.

Diagnostics are reported at the op's definition and name the codegen and
a rule that produces the op, if any.`,
	Run: run,
}

func run(pass *analysis.Pass) error {
	genDir := genDir(pass)
	compileDir := filepath.Join(genDir, "..", "..")
	for _, a := range arches(pass) {
		cg := loadCodegen(filepath.Join(compileDir, strings.ToLower(a.Name)), a.Name)
		if cg == nil || len(cg.simdCases) == 0 {
			continue
		}
		defs := opDefs(genDir, a.Name)
		producers := producers(pass, a)
		for _, op := range a.Ops {
			pos, ok := defs[op.Name]
			if !ok {
				continue
			}
			report := func(format string, args ...any) {
				msg := fmt.Sprintf(format, args...)
				if r := producers[op]; r != nil {
					msg += fmt.Sprintf(" (produced by %s:%d)", filepath.Base(r.Pos.File), r.Pos.Line)
				} else {
					msg += " (latent: no rule produces it)"
				}
				pass.Report(pos, msg)
			}
			if strings.HasPrefix(filepath.Base(pos.File), "simd") && len(cg.cases[op.Name]) == 0 {
				report("%s has no codegen: compiling it fails with \"genValue not implemented\"", op.Name)
			}
			check(a, cg, op, report)
		}
	}
	return nil
}

func check(a *ops.Arch, cg *codegen, op *ops.Op, report func(string, ...any)) {
	clauses := cg.simdCases[op.Name]
	if len(clauses) == 0 {
		return
	}
	if len(cg.cases[op.Name]) != len(clauses) {
		// Also handled outside the SIMD dispatch (as in ssa.go),
		// which may take precedence.
		return
	}
	f := newFacts()
	var helpers []string
	for _, cl := range clauses {
		cf := cg.clauseFacts(cl)
		f.merge(cf)
		helpers = append(helpers, cf.helpers...)
	}
	slices.Sort(helpers)
	helpers = slices.Compact(helpers)
	emitter := fmt.Sprintf("%s:%d", filepath.Base(clauses[0].pos.Filename), clauses[0].pos.Line)
	if len(helpers) > 0 {
		emitter += " (" + strings.Join(helpers, ", ") + ")"
	}

	if !f.opaque {
		switch {
		case op.Aux != "" && !f.aux:
			report("%s has aux %s, but its codegen at %s never reads v.AuxInt or v.Aux: the %s is dropped", op.Name, op.Aux, emitter, auxWhat(op.Aux))
		case op.Aux == "SymValAndOff" && !f.auxVO:
			report("%s has aux SymValAndOff, but its codegen at %s does not decode it with AuxValAndOff: the packed immediate is added to the address", op.Name, emitter)
		}
	}
	if op.Aux == "" && f.aux {
		report("%s has no aux, but its codegen at %s reads it: the value is always 0", op.Name, emitter)
	}

	if !f.opaque && !f.allArgs {
		for i := range int(op.ArgLength) {
			if i >= len(op.Reg.Inputs) || op.Reg.Inputs[i].Empty() {
				continue // memory, or not in a register
			}
			if f.args[i] || i == 0 && op.ResultInArg0 {
				continue
			}
			report("%s takes arg%d in a register, but its codegen at %s never reads v.Args[%d]: the argument is ignored", op.Name, i, emitter, i)
		}
	}
	if op.ArgLength >= 0 && f.maxArgIdx >= int(op.ArgLength) {
		report("%s has %d args, but its codegen at %s reads v.Args[%d]: the compiler panics", op.Name, op.ArgLength, emitter, f.maxArgIdx)
	}

	checkZeroing(a, cg, op, emitter, report)
}

// checkZeroing checks that AVX-512 masked ops are emitted with
// zeroing-masking exactly when they are not merging ops.
func checkZeroing(a *ops.Arch, cg *codegen, op *ops.Op, emitter string, report func(string, ...any)) {
	if len(cg.zeroing) == 0 || a.SIMDMaskRegs.Empty() {
		return
	}
	var masked bool
	for _, in := range op.Reg.Inputs {
		masked = masked || !in.Empty() && in.SubsetOf(a.SIMDMaskRegs)
	}
	vecOut := len(op.Reg.Outputs) > 0 && !op.Reg.Outputs[0].Intersect(a.SIMDRegMask.Minus(a.SIMDMaskRegs)).Empty()
	_, zero := cg.zeroing[op.Name]
	merging := strings.HasSuffix(op.Name, "Merging")
	switch {
	case zero && !masked:
		report("%s is emitted with zeroing-masking ({z}), but it takes no mask", op.Name)
	case zero && merging:
		report("%s is a merging op, but it is emitted with zeroing-masking ({z}): masked-off lanes become 0 instead of arg0's", op.Name)
	case !zero && masked && vecOut && !merging && !isBlend(op):
		report("%s is masked, but its codegen at %s does not emit zeroing-masking ({z}): masked-off lanes keep the output register's previous contents", op.Name, emitter)
	}
}

// isBlend reports whether op is a mask-controlled blend, which is defined by
// merging-masking: VPBLENDM* and VBLENDM* select arg1 where the mask is set
// and arg0 elsewhere.
func isBlend(op *ops.Op) bool {
	asm := strings.TrimPrefix(op.Asm, "V")
	return strings.HasPrefix(asm, "PBLENDM") || strings.HasPrefix(asm, "BLENDM")
}

func auxWhat(aux string) string {
	switch {
	case strings.HasPrefix(aux, "Sym"):
		return "symbol and offset"
	default:
		return "immediate"
	}
}

// arches returns the machine arches of the rule sets being analyzed.
func arches(pass *analysis.Pass) []*ops.Arch {
	var as []*ops.Arch
	seen := make(map[*ops.Arch]bool)
	for _, s := range pass.Sets {
		if a := s.Arch; !a.Generic && !seen[a] {
			seen[a] = true
			as = append(as, a)
		}
	}
	return as
}

// producers maps each op of a to the first rule whose result produces it.
func producers(pass *analysis.Pass, a *ops.Arch) map[*ops.Op]*rules.Rule {
	m := make(map[*ops.Op]*rules.Rule)
	for _, s := range pass.Sets {
		if s.Arch != a {
			continue
		}
		for _, r := range s.Rules {
			for _, v := range r.ResultValues() {
				v.Walk(func(v *rules.Value) bool {
					if v.Op != nil && m[v.Op] == nil {
						m[v.Op] = r
					}
					return true
				})
			}
		}
	}
	return m
}

// genDir returns the _gen directory being analyzed. It prefers the
// directory of the rules files to pass.Ops.Dir, because ops.Load shares
// tables (and their Dir) between trees with identical _gen Go sources.
func genDir(pass *analysis.Pass) string {
	for _, s := range pass.Sets {
		for _, f := range s.Files {
			return filepath.Dir(f.Path)
		}
	}
	return pass.Ops.Dir
}
